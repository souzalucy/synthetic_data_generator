"""Ground-truth graph construction from known user-to-log mappings.

Replaces the probabilistic/heuristic device stitching (IP, GPS, behavioral
fingerprinting) with a deterministic ground-truth graph built directly from
the real ``user_id`` present in every ground-truth event.

The ground-truth events are generated by :class:`BaseStream` and stored in
``BaseStream.events_ground_truth`` — they always contain the real ``user_id``
and are never exported to JSONL (privacy-preserving).

Three graph views are provided:
    1. **User→Device graph** — bipartite graph connecting users to their devices.
    2. **User→Event graph** — bipartite graph connecting users to their log events.
    3. **User→Log graph** — same as User→Event, with richer metadata on edges.
"""

from typing import Dict, List, Optional, Any
from collections import defaultdict

import networkx as nx


class GroundTruthGraphBuilder:
    """Builds deterministic ground-truth graphs from known user-to-log mappings.

    No heuristics, no probabilistic matching — every edge is a fact derived
    from the ground-truth event metadata.

    Usage::

        gt_graphs = GroundTruthGraphBuilder.build_all(ground_truth_events)
        user_device = gt_graphs["user_device"]
        user_event  = gt_graphs["user_event"]
        user_log    = gt_graphs["user_log"]
    """

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    @staticmethod
    def build_all(
        ground_truth_events: List[Dict],
    ) -> Dict[str, nx.Graph]:
        """Build all three ground-truth graph views in one call.

        Args:
            ground_truth_events: List of ground-truth event dicts, each
                containing at least ``user_id``, ``event_id``, ``device_id``,
                ``service``, ``event_type``, and ``timestamp``.

        Returns:
            Dict with keys ``"user_device"``, ``"user_event"``, ``"user_log"``
            mapping to their respective :class:`networkx.Graph` instances.
        """
        return {
            "user_device": GroundTruthGraphBuilder.build_user_device_graph(
                ground_truth_events
            ),
            "user_event": GroundTruthGraphBuilder.build_user_event_graph(
                ground_truth_events
            ),
            "user_log": GroundTruthGraphBuilder.build_user_log_graph(
                ground_truth_events
            ),
        }

    @staticmethod
    def build_user_device_graph(
        ground_truth_events: List[Dict],
    ) -> nx.Graph:
        """Build a bipartite graph: User nodes ↔ Device nodes.

        An edge ``user:U -- device:D`` means "user U generated logs from
        device D."  This is the ground truth for device-stitching evaluation.

        Args:
            ground_truth_events: List of ground-truth event dicts.

        Returns:
            NetworkX Graph with node attribute ``type`` in {"user", "device"}.
        """
        G = nx.Graph()
        for event in ground_truth_events:
            uid = event.get("user_id")
            did = event.get("device_id")
            if not uid or not did:
                continue
            user_node = f"user:{uid}"
            device_node = f"device:{did}"
            G.add_node(user_node, type="user", label=str(uid))
            G.add_node(device_node, type="device", label=str(did))
            G.add_edge(user_node, device_node, weight=1.0)
        return G

    @staticmethod
    def build_user_event_graph(
        ground_truth_events: List[Dict],
    ) -> nx.Graph:
        """Build a bipartite graph: User nodes ↔ Event nodes.

        An edge ``user:U -- event:E`` means "user U is the author of event E."
        This is the ground truth for the interaction-graph layer.

        Args:
            ground_truth_events: List of ground-truth event dicts.

        Returns:
            NetworkX Graph with node attribute ``type`` in {"user", "event"}.
        """
        G = nx.Graph()
        for event in ground_truth_events:
            uid = event.get("user_id")
            eid = event.get("event_id")
            if not uid or not eid:
                continue
            user_node = f"user:{uid}"
            event_node = f"event:{eid}"
            G.add_node(user_node, type="user", label=str(uid))
            G.add_node(
                event_node,
                type="event",
                label=str(eid),
                service=event.get("service", ""),
                event_type=event.get("event_type", ""),
                timestamp=event.get("timestamp", ""),
            )
            G.add_edge(
                user_node,
                event_node,
                weight=1.0,
                service=event.get("service", ""),
                event_type=event.get("event_type", ""),
                timestamp=event.get("timestamp", ""),
            )
        return G

    @staticmethod
    def build_user_log_graph(
        ground_truth_events: List[Dict],
    ) -> nx.Graph:
        """Build a graph: User nodes ↔ Log-entry nodes (richer metadata).

        This is the purest ground-truth view — every edge represents the
        provenance of a log line: "this user generated this log entry."

        Edge attributes include ``service``, ``event_type``, and ``timestamp``
        for downstream filtering and analysis.

        Args:
            ground_truth_events: List of ground-truth event dicts.

        Returns:
            NetworkX Graph with node attribute ``type`` in {"user", "log"}.
        """
        G = nx.Graph()
        for event in ground_truth_events:
            uid = event.get("user_id")
            log_id = event.get("event_id")
            if not uid or not log_id:
                continue
            G.add_node(uid, type="user", label=f"User {uid}")
            G.add_node(
                f"log:{log_id}",
                type="log",
                label=f"Log {log_id[:16]}...",
                service=event.get("service", ""),
                event_type=event.get("event_type", ""),
                timestamp=event.get("timestamp", ""),
            )
            G.add_edge(
                uid,
                f"log:{log_id}",
                weight=1.0,
                service=event.get("service", ""),
                event_type=event.get("event_type", ""),
                timestamp=event.get("timestamp", ""),
            )
        return G

    # ------------------------------------------------------------------
    # Metrics
    # ------------------------------------------------------------------

    @staticmethod
    def compute_metrics(graph: nx.Graph) -> Dict[str, Any]:
        """Compute summary metrics for a ground-truth graph.

        Args:
            graph: A NetworkX graph produced by one of the ``build_*`` methods.

        Returns:
            Dict with keys:
            - ``n_user_nodes``: number of user-type nodes
            - ``n_log_nodes``: number of log/event/device-type nodes
            - ``n_edges``: total edges
            - ``avg_logs_per_user``: average number of logs per user
            - ``n_users_with_logs``: users that have at least one log
            - ``service_distribution``: dict mapping service → edge count
        """
        user_nodes = {
            n for n, d in graph.nodes(data=True) if d.get("type") in ("user",)
        }
        log_nodes = {
            n
            for n, d in graph.nodes(data=True)
            if d.get("type") in ("log", "event", "device")
        }

        n_users = len(user_nodes)
        n_logs = len(log_nodes)
        n_edges = graph.number_of_edges()

        # Service distribution (from edge attributes)
        service_counts: Dict[str, int] = defaultdict(int)
        for _, _, data in graph.edges(data=True):
            svc = data.get("service", "unknown")
            service_counts[svc] += 1

        return {
            "n_user_nodes": n_users,
            "n_log_nodes": n_logs,
            "n_edges": n_edges,
            "avg_logs_per_user": round(n_edges / max(n_users, 1), 2),
            "n_users_with_logs": n_users,
            "service_distribution": dict(service_counts),
        }

    # ------------------------------------------------------------------
    # Export helpers
    # ------------------------------------------------------------------

    @staticmethod
    def to_serializable(graph: nx.Graph) -> Dict[str, Any]:
        """Convert a ground-truth graph to a JSON-serializable dict.

        Args:
            graph: A NetworkX graph.

        Returns:
            Dict with ``"nodes"`` and ``"edges"`` lists suitable for JSON
            serialization.
        """
        nodes = []
        for n, d in graph.nodes(data=True):
            node_entry: Dict[str, Any] = {"id": str(n)}
            node_entry.update({k: v for k, v in d.items() if v is not None})
            nodes.append(node_entry)

        edges = []
        for u, v, d in graph.edges(data=True):
            edge_entry: Dict[str, Any] = {"source": str(u), "target": str(v)}
            edge_entry.update({k: v for k, v in d.items() if v is not None})
            edges.append(edge_entry)

        return {
            "nodes": nodes,
            "edges": edges,
            "n_nodes": len(nodes),
            "n_edges": len(edges),
        }
